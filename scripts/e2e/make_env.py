"""
Creates e2e/.env.e2e for the isolated e2e stack. Prints nothing secret.

    python -m scripts.e2e.make_env [--llm-key-from .env]

- Database / Redis / storage / email point only at the local e2e containers
  (docker-compose.e2e.yml also forces them): no live host is ever written.
- Fresh encryption keys are generated for every key alias - never copied.
- Supabase / UMS / JWKS get placeholders on the reserved .invalid domain,
  which never resolves - nothing can connect to them.
- The re-parse check needs a real LLM to parse the anonymised fixtures.
  --llm-key-from copies ONLY the Gemini key/model from the given env file,
  without printing them. Without it, set GEMINI_API_KEY in .env.e2e yourself.
"""
import argparse
from pathlib import Path

from cryptography.fernet import Fernet
from dotenv import dotenv_values

OUT = Path(__file__).resolve().parents[2] / "e2e" / ".env.e2e"
KEY_ALIASES = ("candidate-pii-v1", "ai-provider-v1", "oauth-token-v1")
LLM_KEYS = ("GEMINI_API_KEY", "GEMINI_MODEL")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--llm-key-from", help="env file to copy GEMINI_API_KEY/GEMINI_MODEL from (not printed)")
    parser.add_argument("--force", action="store_true", help="overwrite an existing .env.e2e")
    args = parser.parse_args()
    if OUT.exists() and not args.force:
        raise SystemExit(f"{OUT.name} already exists - use --force to regenerate it.")

    lines = [
        "# Isolated e2e stack only - generated by scripts/e2e/make_env.py. Never reaches live systems.",
        "APP_ENV=e2e", "DEBUG=False",
        "DB_USER=airs_e2e", "DB_PASSWORD=airs_e2e", "DB_HOST=postgres", "DB_PORT=5432", "DB_NAME=airs_e2e", "DB_SSLMODE=disable",
        "REDIS_HOST=redis", "REDIS_PORT=6379", "REDIS_PASSWORD=",
        "EMAIL_DELIVERY=log", "STORAGE_BACKEND=local", "LOCAL_STORAGE_DIR=/data/storage",
        "AWS_ACCESS_KEY_ID=", "AWS_SECRET_ACCESS_KEY=", "SES_FROM_EMAIL=e2e@example.invalid",
        "SUPABASE_URL=https://storage.e2e.invalid", "SUPABASE_PUBLISHABLE_KEY=e2e-placeholder",
        "SUPABASE_SECRET_KEY=e2e-placeholder", "SUPABASE_JWKS_URL=https://auth.e2e.invalid/jwks",
        "UMS_URL=https://ums.e2e.invalid", "CORS_ORIGINS=http://localhost:5173",
        "FRONTEND_BASE_URL=http://localhost:5173",
    ]
    for alias in KEY_ALIASES:
        lines.append(f"ENCRYPTION_KEY_{alias.upper().replace('-', '_')}={Fernet.generate_key().decode()}")

    copied = 0
    if args.llm_key_from:
        source = dotenv_values(args.llm_key_from)
        for key in LLM_KEYS:
            if source.get(key):
                lines.append(f"{key}={source[key]}")
                copied += 1
    else:
        lines.append("GEMINI_API_KEY=")

    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {OUT.relative_to(OUT.parents[1])} (fresh encryption keys; LLM settings copied: {copied}).")


if __name__ == "__main__":
    main()
