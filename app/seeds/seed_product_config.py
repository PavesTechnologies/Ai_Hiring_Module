"""
Product configuration built in dev, for a fresh database - run after the
migrations and the other seeds (the skill catalogue must exist first):

    python -m app.seeds.seed_product_config            # apply the approved sections
    python -m app.seeds.seed_product_config --dry-run  # show what it would do; changes nothing
    ... --data-dir <dir>                                # other data files (e.g. a review rehearsal)

Data: app/seeds/product_config/*.json, generated by
scripts/config_seed/build_seed_data.py from a reviewed diff of dev against a
fresh database. Only sections marked "approved" load; the dev-added skills and
the settings production must decide stay unapproved until reviewed.

Idempotent, and never overwrites an edit made after seeding:
  - add:    insert when the row is missing; leave an existing row alone
  - change: set a field only while it still holds the value this database
            was seeded with ("from"); a field already at "to" is done; any
            other value was edited here, so it is kept and reported
  - rename: only while the old row is untouched and the new name is free
Rows that name a skill or certification which doesn't exist (yet) are
skipped and reported. Nothing is ever deleted. Never sends email.
"""
import glob
import json
import os
import sys
from collections import Counter, defaultdict

from sqlalchemy import text

from app.seeds.product_config_spec import TABLES, plain, row_key

DATA_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "product_config")
FILE_ORDER = ["catalogue.json", "catalogue_dev_added.json", "scoring_rules.json", "platform.json",
              "platform_pending_decision.json"]
UNTOUCHED_SOURCES = {None, "SEED_STOPGAP"}       # a seeded stop-gap skill nobody has edited


class MissingDependency(Exception):
    pass


# --- planning: pure, no database ------------------------------------------------------------

def plan_add(current: dict | None, values: dict, fields: list[str]) -> tuple[str, dict]:
    if current is None:
        return "insert", values
    differing = [f for f in fields if current.get(f) != values.get(f)]
    return ("noop", {}) if not differing else ("exists", {f: values.get(f) for f in differing})


def plan_change(current: dict | None, change: dict) -> tuple[str, dict]:
    if current is None:
        return "missing", {}
    updates, edited = {}, []
    for field, step in change.items():
        if current.get(field) == step["to"]:
            continue
        if current.get(field) == step["from"]:
            updates[field] = step["to"]
        else:
            edited.append(field)
    if edited:
        return "edited", {"fields": edited, "updates": updates}
    return ("update", updates) if updates else ("noop", {})


def without_unresolvable_parent(values: dict, known_skills: set[str]) -> tuple[dict, str | None]:
    """A skill's parent that doesn't exist (yet) isn't planned - it waits, reported once."""
    parent = values.get("parent")
    if parent and parent not in known_skills:
        return {k: v for k, v in values.items() if k != "parent"}, parent
    return values, None


def load_sections(data_dir: str = DATA_DIR) -> list[tuple[str, dict]]:
    present = {os.path.basename(p) for p in glob.glob(os.path.join(data_dir, "*.json"))}
    unknown = present - set(FILE_ORDER)
    if unknown:
        raise SystemExit(f"unknown seed files (add them to FILE_ORDER): {sorted(unknown)}")
    out = []
    for name in FILE_ORDER:
        if name in present:
            content = json.load(open(os.path.join(data_dir, name), encoding="utf-8"))
            out += [(name, section) for section in content["sections"]]
    return out


# --- applying ---------------------------------------------------------------------------------

def _models():
    import app.models  # noqa: F401
    from app.models.config import PlatformConfig
    from app.models.embeddings import EmbeddingModelVersion
    from app.models.prompt_template import PromptTemplate
    from app.models.scoring_v2 import Certification, CertificationSkill, SkillPatternRule, SkillSense
    from app.models.skills import SkillOntology
    return {"skill_ontology": SkillOntology, "skill_senses": SkillSense, "skill_pattern_rules": SkillPatternRule,
            "certification_skills": CertificationSkill, "platform_config": PlatformConfig,
            "prompt_templates": PromptTemplate, "embedding_model_versions": EmbeddingModelVersion,
            "certifications": Certification}


class _Applier:
    def __init__(self, db):
        self.db = db
        self.models = _models()

    # natural key / references -> the ORM row and its column values
    def skill_id(self, name):
        Skill = self.models["skill_ontology"]
        row = self.db.query(Skill).filter(Skill.canonical_name == name).one_or_none()
        if row is None:
            raise MissingDependency(f"skill {name!r}")
        return row.id

    def find(self, table, key: dict):
        M = self.models[table]
        q = self.db.query(M)
        if table == "skill_ontology":
            return q.filter(M.canonical_name == key["canonical_name"]).one_or_none()
        if table == "skill_senses":
            return q.filter(M.canonical_skill_id == self.skill_id(key["skill"]), M.sense_key == key["sense_key"]).one_or_none()
        if table == "skill_pattern_rules":
            return q.filter(M.name == key["name"]).one_or_none()
        if table == "certification_skills":
            cert = self.db.query(self.models["certifications"]).filter_by(name=key["certification"]).one_or_none()
            if cert is None:
                raise MissingDependency(f"certification {key['certification']!r}")
            return q.filter(M.certification_id == cert.id, M.canonical_skill_id == self.skill_id(key["skill"])).one_or_none()
        if table == "platform_config":
            return q.filter(M.key == key["key"]).one_or_none()
        if table == "prompt_templates":
            return q.filter(M.task_type == key["task_type"], M.name == key["name"]).one_or_none()
        if table == "embedding_model_versions":
            return q.filter(M.model_name == key["model_name"], M.model_version == key["model_version"]).one_or_none()
        raise ValueError(table)

    def columns(self, table, values: dict) -> dict:
        """Export-form values -> model attributes (names resolved to ids, enums converted)."""
        M = self.models[table]
        out = {}
        for field, value in values.items():
            if field == "parent":
                continue                                    # second pass, once every skill exists
            if field == "skill":
                out["canonical_skill_id"] = self.skill_id(value)
                continue
            if field == "certification":
                cert = self.db.query(self.models["certifications"]).filter_by(name=value).one_or_none()
                if cert is None:
                    raise MissingDependency(f"certification {value!r}")
                out["certification_id"] = cert.id
                continue
            column = M.__table__.columns[field]
            enum_class = getattr(column.type, "enum_class", None)
            out[field] = enum_class(value) if (enum_class is not None and value is not None) else value
        return out


def run(db, *, dry_run: bool, data_dir: str = DATA_DIR, out=print) -> dict:
    applier = _Applier(db)
    totals = defaultdict(Counter)
    notes = defaultdict(list)
    parents = []                                            # (skill name, parent name, only if empty)

    def current_rows(table):
        keys, fields, sql = TABLES[table]
        return {row_key(dict(r._mapping), keys): {k: plain(v) for k, v in dict(r._mapping).items()}
                for r in db.execute(text(sql))}

    for file_name, section in load_sections(data_dir):
        table = section["table"]
        label = f"{file_name}:{table}"
        if not section["approved"]:
            totals[label]["skipped (not approved)"] += len(section["add"]) + len(section["change"])
            continue
        fields = section["fields"]
        current = current_rows(table)
        renamed = set()
        for old, new in section.get("renames", {}).items():
            old_key, new_key = json.dumps([old]), json.dumps([new])
            if old_key in current and new_key not in current and current[old_key].get("source") in UNTOUCHED_SOURCES:
                applier.find(table, {"canonical_name": old}).canonical_name = new
                renamed.add(new_key)
                totals[label]["renamed"] += 1
        if renamed:
            db.flush()
            current = current_rows(table)

        known_skills = set()
        if table == "skill_ontology":
            known_skills = {json.loads(k)[0] for k in current} | {json.loads(k)[0] for k in section["add"]}
        for key, values in section["add"].items():
            try:
                plan_fields = fields
                if table == "skill_ontology":
                    values, waiting = without_unresolvable_parent(values, known_skills)
                    if waiting:
                        plan_fields = [f for f in fields if f != "parent"]
                        parents.append((json.loads(key)[0], waiting, True))   # set at the end if it exists by then
                action, detail = plan_add(current.get(key), values, plan_fields)
                if key in renamed and action == "exists":
                    action = "update"                       # the renamed seed row takes dev's values
                if (action == "exists" and set(detail) == {"parent"}
                        and not (current.get(key) or {}).get("parent")):
                    action = "update"                       # filling a parent left empty, not an edit
                if action == "insert":
                    db.add(applier.models[table](**applier.columns(table, values)))
                elif action == "update":
                    row = applier.find(table, dict(zip(section["keys"], json.loads(key))))
                    for attr, value in applier.columns(table, detail).items():
                        setattr(row, attr, value)
                elif action == "exists":
                    notes[label].append(f"{key}: exists with other values {sorted(detail)} - kept")
                if table == "skill_ontology" and values.get("parent") and action in ("insert", "update"):
                    parents.append((values["canonical_name"], values["parent"], False))
                totals[label][action] += 1
            except MissingDependency as exc:
                totals[label]["skipped (missing dependency)"] += 1
                notes[label].append(f"{key}: needs {exc}")
        db.flush()

        for key, change in section["change"].items():
            try:
                if table == "skill_ontology" and "parent" in change:
                    _, waiting = without_unresolvable_parent({"parent": change["parent"]["to"]}, known_skills)
                    if waiting:
                        change = {f: step for f, step in change.items() if f != "parent"}
                        parents.append((json.loads(key)[0], waiting, True))
                action, detail = plan_change(current.get(key), change)
                updates = detail.get("updates", detail) if action in ("update", "edited") else {}
                if updates:
                    row = applier.find(table, dict(zip(section["keys"], json.loads(key))))
                    if "parent" in updates:
                        parents.append((json.loads(key)[0], updates.pop("parent"), False))
                    for attr, value in applier.columns(table, updates).items():
                        setattr(row, attr, value)
                if action == "edited":
                    notes[label].append(f"{key}: {detail['fields']} edited here - kept")
                totals[label][action] += 1
            except MissingDependency as exc:
                totals[label]["skipped (missing dependency)"] += 1
                notes[label].append(f"{key}: needs {exc}")
        db.flush()

    for name, parent, only_if_empty in parents:
        try:
            row = applier.find("skill_ontology", {"canonical_name": name})
            if row is None or (only_if_empty and row.parent_skill_id is not None):
                continue
            parent_id = applier.skill_id(parent) if parent else None
            if row.parent_skill_id != parent_id:
                row.parent_skill_id = parent_id
                totals["skill parents"]["set"] += 1
        except MissingDependency as exc:
            notes["skill parents"].append(f"{name}: parent {exc} not in the catalogue (yet) - left empty")
    db.flush()

    for label, counts in totals.items():
        out(f"{label}: {dict(counts)}")
    for label, lines in notes.items():
        for line in lines[:20]:
            out(f"  {label} - {line}")
        if len(lines) > 20:
            out(f"  {label} - ... {len(lines) - 20} more")
    if dry_run:
        db.rollback()
        out("dry run - nothing changed")
    else:
        db.commit()
    return {label: dict(c) for label, c in totals.items()}


if __name__ == "__main__":
    from app.db.session import SessionLocal
    session = SessionLocal()
    try:
        data_dir = sys.argv[sys.argv.index("--data-dir") + 1] if "--data-dir" in sys.argv else DATA_DIR
        run(session, dry_run="--dry-run" in sys.argv, data_dir=data_dir)
    finally:
        session.close()
